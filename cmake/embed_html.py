#!/usr/bin/env python3
"""Embeds a single HTML file as a C++ string_view header.
Usage: embed_html.py <input.html> <output.h>
"""
import sys

with open(sys.argv[1], "rb") as f:
    data = f.read()

hex_bytes = ", ".join(f"0x{b:02x}" for b in data)

with open(sys.argv[2], "w") as out:
    out.write("// Auto-generated by embed_html.py — do not edit\n")
    out.write("#pragma once\n")
    out.write("#include <string_view>\n\n")
    out.write("namespace jrnl {\n\n")
    out.write(f"static const unsigned char _html_data[] = {{ {hex_bytes} }};\n\n")
    out.write(f"inline const std::string_view frontend_html{{\n")
    out.write(f"    reinterpret_cast<const char*>(_html_data), {len(data)}\n")
    out.write("};\n\n")
    out.write("} // namespace jrnl\n")
