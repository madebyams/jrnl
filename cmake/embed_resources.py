#!/usr/bin/env python3
"""
Walks FRONTEND_DIST, embeds every file as an unsigned char[] in a generated
.cpp/.h pair that exposes jrnl::embedded_files().
Usage: embed_resources.py <frontend_dist> <output.cpp> <output.h>
"""

import os
import sys


def c_ident(path: str) -> str:
    return "f_" + "".join(c if c.isalnum() else "_" for c in path)


def main():
    if len(sys.argv) != 4:
        print(f"Usage: {sys.argv[0]} <frontend_dist> <output.cpp> <output.h>")
        sys.exit(1)

    dist_dir, out_cpp, out_h = sys.argv[1], sys.argv[2], sys.argv[3]

    entries = []  # (url_path, var_name, bytes)
    for root, _, filenames in os.walk(dist_dir):
        for name in sorted(filenames):
            filepath = os.path.join(root, name)
            relpath = os.path.relpath(filepath, dist_dir).replace("\\", "/")
            with open(filepath, "rb") as f:
                data = f.read()
            entries.append(("/" + relpath, c_ident(relpath), data))

    with open(out_h, "w") as h:
        h.write("// Auto-generated by embed_resources.py — do not edit\n")
        h.write("#pragma once\n")
        h.write("#include <string>\n")
        h.write("#include <string_view>\n")
        h.write("#include <unordered_map>\n\n")
        h.write("namespace jrnl {\n\n")
        h.write("const std::unordered_map<std::string, std::string_view>& embedded_files();\n\n")
        h.write("} // namespace jrnl\n")

    with open(out_cpp, "w") as c:
        c.write("// Auto-generated by embed_resources.py — do not edit\n")
        c.write('#include "embedded_frontend.h"\n\n')
        c.write("namespace jrnl {\n\n")

        for url_path, var_name, data in entries:
            hex_bytes = ", ".join(f"0x{b:02x}" for b in data)
            c.write(f"// {url_path}\n")
            c.write(f"static const unsigned char {var_name}[] = {{ {hex_bytes} }};\n\n")

        c.write("const std::unordered_map<std::string, std::string_view>& embedded_files() {\n")
        c.write("    static const std::unordered_map<std::string, std::string_view> files = {\n")
        for url_path, var_name, data in entries:
            c.write(f'        {{ "{url_path}", std::string_view(reinterpret_cast<const char*>({var_name}), {len(data)}) }},\n')
        c.write("    };\n")
        c.write("    return files;\n")
        c.write("}\n\n")
        c.write("} // namespace jrnl\n")

    print(f"Embedded {len(entries)} file(s) from {dist_dir}")


if __name__ == "__main__":
    main()
